"""Build the coarse dirt/grass mask used for footstep dust and sounds.

The mask is derived from camp-hillside.webp (the exact art the avatar walks on), so dust only
appears over visibly bare earth. Output: src/core/fx/surface-mask.ts (1 = dirt, 0 = anything else).
"""
from pathlib import Path
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
WORLD_W, WORLD_H, CELL = 1000, 650, 10
img = Image.open(ROOT / 'public/assets/camp-hillside.webp').convert('RGBA').resize((WORLD_W, WORLD_H), Image.BILINEAR)
rgb = np.array(img).astype(int)
r, g, b, a = rgb[..., 0], rgb[..., 1], rgb[..., 2], rgb[..., 3]
# Dirt in the art is a warm tan: red clearly above green, green above blue, medium-high brightness.
dirt = (a > 200) & (r > 180) & (r - g > 22) & (r - g < 70) & (g - b > 35) & (g > 120)
cols, rows = WORLD_W // CELL, WORLD_H // CELL
lines = []
for row in range(rows):
    line = ''
    for col in range(cols):
        block = dirt[row * CELL:(row + 1) * CELL, col * CELL:(col + 1) * CELL]
        line += '1' if block.mean() > .5 else '0'
    lines.append(line)
body = ',\n  '.join(f"'{line}'" for line in lines)
(ROOT / 'src/core/fx/surface-mask.ts').write_text(
    "// Generated by tools/surface_mask.py from camp-hillside.webp. Do not edit by hand.\n"
    f"export const DIRT_CELL = {CELL}\nexport const DIRT_MASK: readonly string[] = [\n  {body},\n]\n", encoding='utf-8')
# Preview for review: dirt in red over the art.
preview = np.array(img.convert('RGB'))
mask = np.kron(np.array([[c == '1' for c in line] for line in lines]), np.ones((CELL, CELL), bool))
preview[mask] = (preview[mask] * .4 + np.array([255, 0, 0]) * .6).astype('uint8')
Image.fromarray(preview).save(ROOT / 'tools/surface_mask_preview.png')
print('dirt cells', sum(line.count('1') for line in lines), 'of', cols * rows)
